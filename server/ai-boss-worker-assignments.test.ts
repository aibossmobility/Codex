import assert from "node:assert/strict";
import Database from "better-sqlite3";
import { randomUUID } from "node:crypto";
import { ensureExecutiveActionQueueTables } from "./executive-action-queue-store";
import { queueWorkerAssignment } from "./ai-boss-worker-assignments";

const db = new Database(":memory:");
db.pragma("foreign_keys=OFF");
ensureExecutiveActionQueueTables(db);
const original = { project:"papa-life", role:"seo-website", instruction:"Review Papa Life website navigation and prepare a read-only report.", request_id:randomUUID() };
const first = queueWorkerAssignment(db, original);
assert.equal(first.status,"awaiting_approval");
const duplicate = queueWorkerAssignment(db,original);
assert.equal(duplicate.id,first.id);
assert.equal(duplicate.reused,true);
assert.equal(db.prepare("select count(*) as n from executive_actions").get()!.n,1);
const action = db.prepare("select * from executive_actions where id=?").get(first.id) as any;
const payload=JSON.parse(action.action_payload_json);
assert.equal(action.approval_required,1);
assert.equal(action.execution_route,"local");
assert.equal(action.provider_id,null);
assert.equal(action.estimated_external_ai_cost_micros,0);
assert.equal(payload.mode,"read_only");
assert.equal(payload.no_purchases,true);
assert.equal(payload.no_writes,true);
assert.equal(payload.no_outreach,true);
assert.equal(action.project_key,"papa-life");
assert.throws(()=>queueWorkerAssignment(db,{...original,project:"ai-boss-mobility"}));
assert.throws(()=>queueWorkerAssignment(db,{...original,request_id:randomUUID(),project:"ai-boss-mobility",role:"papa-life-director"}));
assert.throws(()=>queueWorkerAssignment(db,{...original,request_id:randomUUID(),role:"ai-boss-mobility-director"}));
assert.throws(()=>queueWorkerAssignment(db,{...original,request_id:randomUUID(),unauthorized:true}));
assert.throws(()=>queueWorkerAssignment(db,{...original,request_id:randomUUID(),instruction:"send money"}));
assert.equal(db.prepare("select count(*) as n from executive_actions").get()!.n,1);
const ghl = queueWorkerAssignment(db,{...original,role:"ghl-customer-service",project:"ai-boss-mobility",request_id:randomUUID(),instruction:"Review customer estimate and pipeline concerns without modifying GHL."});
assert.equal(ghl.status,"awaiting_approval");
const ghlRow = db.prepare("select * from executive_actions where id=?").get(ghl.id) as any;
assert.equal(ghlRow.project_key,"ai-boss-mobility");
assert.equal(ghlRow.estimated_external_ai_cost_micros,0);
assert.equal(JSON.parse(ghlRow.action_payload_json).no_writes,true);
db.close();
console.log("Worker assignment intake safety: passed, approval required, duplicate safe, no model/provider cost");
