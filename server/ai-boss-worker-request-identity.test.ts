import assert from "node:assert/strict";
import Database from "better-sqlite3";
import {randomUUID} from "node:crypto";
import {ensureExecutiveActionQueueTables} from "./executive-action-queue-store";
import {acceptVerifiedClaim} from "./ai-boss-worker-mac-poller";
const db=new Database(":memory:");
db.exec("CREATE TABLE IF NOT EXISTS human_impact_observations (id INTEGER PRIMARY KEY)");
ensureExecutiveActionQueueTables(db);
db.exec("CREATE TABLE ai_boss_worker_remote_map (remote_action_id INTEGER PRIMARY KEY, local_action_id INTEGER NOT NULL UNIQUE, project TEXT NOT NULL, role TEXT NOT NULL, instruction TEXT NOT NULL)");
db.prepare("INSERT INTO ai_boss_worker_remote_map VALUES(1,94,?,?,?)").run("papa-life","seo-website","old task");
const a={action_id:1,project:"papa-life",role:"seo-website",instruction:"Check the Papa Life website links and produce a saved report",request_id:randomUUID(),lease:randomUUID()};
const first=acceptVerifiedClaim(db,a);
assert.equal(first.reused,false);
assert.equal(acceptVerifiedClaim(db,a).local_action_id,first.local_action_id);
assert.throws(()=>acceptVerifiedClaim(db,{...a,instruction:"Tampered assignment"}));
assert.throws(()=>acceptVerifiedClaim(db,{...a,action_id:7}));
const second=acceptVerifiedClaim(db,{...a,request_id:randomUUID(),lease:randomUUID()});
assert.notEqual(first.local_action_id,second.local_action_id);
assert.equal((db.prepare("SELECT count(*) n FROM ai_boss_worker_remote_map").get() as any).n,1);
assert.equal((db.prepare("SELECT count(*) n FROM ai_boss_worker_request_map").get() as any).n,2);
db.close();
console.log("Mac cloud ID reuse guarded by request UUID, legacy records preserved");
