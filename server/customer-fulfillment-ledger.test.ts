import assert from "node:assert/strict";
import Database from "better-sqlite3";
import { registerVerifiedCustomerOrder,advanceCustomerJob,customerJobSummary } from "./customer-fulfillment-ledger";
const db=new Database(":memory:");
const base={brand:"papa-life" as const,transactionId:"paid-tx-1",orderId:"order-1",productCode:"curriculum.manuscript.module.01",priceCents:1499,email:"customer@example.com",paymentVerified:true,paymentEvidence:"GoHighLevel live transaction + matched order, independently checked"};
for(const patch of [{paymentVerified:false},{priceCents:0},{paymentEvidence:""},{brand:"other"},{email:"invalid"}]) assert.throws(()=>registerVerifiedCustomerOrder(db,{...base,...patch} as any));
const first=registerVerifiedCustomerOrder(db,base);
assert.equal(first.state,"payment_verified");
assert.equal(registerVerifiedCustomerOrder(db,base).reused,true);
assert.throws(()=>registerVerifiedCustomerOrder(db,{...base,priceCents:999}));
assert.throws(()=>advanceCustomerJob(db,first.id,"delivered","fake delivered"));
assert.throws(()=>advanceCustomerJob(db,first.id,"quality_passed","not ready"));
assert.throws(()=>advanceCustomerJob(db,first.id,"production_ready",""));
advanceCustomerJob(db,first.id,"production_ready","Existing protected PDF entitlement granted");
advanceCustomerJob(db,first.id,"quality_passed","Approved product code and PDF file verified accessible");
advanceCustomerJob(db,first.id,"delivered","GoHighLevel access email provider acknowledged delivery request");
assert.throws(()=>advanceCustomerJob(db,first.id,"production_ready","cannot reopen delivered"));
const other=registerVerifiedCustomerOrder(db,{...base,brand:"ai-boss-mobility",productCode:"ai.feasibility.readiness",priceCents:35000});
assert.equal(customerJobSummary(db,"papa-life").length,1);
assert.equal(customerJobSummary(db,"ai-boss-mobility").length,1);
assert.equal(customerJobSummary(db,"ai-boss-mobility")[0].director_role,"ai-boss-mobility-director");
assert.equal((db.prepare("SELECT COUNT(*) AS n FROM customer_fulfillment_events WHERE job_id=?").get(first.id) as any).n,4);
advanceCustomerJob(db,other.id,"needs_attention","Missing customer-supplied data");
assert.throws(()=>advanceCustomerJob(db,other.id,"delivered","not verified"));
advanceCustomerJob(db,other.id,"production_ready","Data supplied and validated");
console.log("PASS: durable tenant-separated paid jobs, idempotency, immutable purchase identity, gated production and QA, exception recovery");
