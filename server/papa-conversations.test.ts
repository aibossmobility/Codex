import assert from 'node:assert/strict';
import { once } from 'node:events';
import Database from 'better-sqlite3';
import express from 'express';
import { ensurePapaConversations, listPapaConversations, savePapaConversation, installPapaConversationRoutes } from './papa-conversations';
import { conversationInView, conversationMissing, papaConversationSchema } from '../shared/papa-conversations';
const db = new Database(':memory:');
ensurePapaConversations(db);
const record = { id: 'df646c1a-9b05-4504-bfcf-d020f2beac13', person: 'Test father', date: '', kind: 'Father', purpose: '', certainty: 'Unknown', questions: ['What matters?', 'What could help?'], stage: 'Presence', prompt: 'How can I listen?', useful: '', takeaways: ['', ''], steps: '', missing: '', topic: '/', completed: false };
savePapaConversation(db, 1, record);
assert.equal(listPapaConversations(db, 1).length, 1);
assert.equal(listPapaConversations(db, 2).length, 0, 'Other administrators cannot read owner notes');
savePapaConversation(db, 2, {...record, person: 'Other owner'});
assert.equal(listPapaConversations(db, 1)[0].person, 'Test father', 'Same ID cannot overwrite another owner');
assert.deepEqual(conversationMissing(papaConversationSchema.parse(record)), ['Date', 'Purpose or interest']);
assert.equal(conversationInView(papaConversationSchema.parse(record), 'Missing information'), true);
assert.equal(papaConversationSchema.safeParse({...record, date: '2026-02-30'}).success, false);
assert.equal(papaConversationSchema.safeParse({...record, completed: true}).success, false);
const complete = savePapaConversation(db, 1, {...record, completed: true, takeaways: ['Listen first', ''], steps: 'Consider one more conversation.'});
assert.equal(listPapaConversations(db, 1)[0].takeaways[0], 'Listen first');
assert.equal(conversationInView(complete, 'Completed reflections'), true);
assert.equal(conversationInView(complete, 'Upcoming'), false);
assert.equal(conversationInView(complete, 'Missing information'), false);
assert.equal(conversationInView({...complete, completed: false, date: '2026-11-08'}, 'Upcoming', '2026-11-09'), false);
assert.equal(conversationInView({...complete, completed: false, date: '2026-11-08'}, 'All conversations', '2026-11-09'), true);
const app = express(); app.use(express.json());
installPapaConversationRoutes(app, db, (req,res,next) => { if (req.get('x-test-owner')) { (req as any).session = {adminId: Number(req.get('x-test-owner'))}; next(); } else res.status(401).json({ok:false}); });
const server=app.listen(0, '127.0.0.1'); await once(server, 'listening'); const addr=server.address() as {port:number}; const url=`http://127.0.0.1:${addr.port}/api/admin/papa-conversations`;
try {
  assert.equal((await fetch(url)).status, 401);
  assert.equal((await fetch(url, {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(record)})).status, 401);
  const read=await fetch(url,{headers:{'x-test-owner':'1'}}); assert.equal(read.headers.get('cache-control'),'no-store');
  const body=await read.json() as any; assert.equal(body.conversations[0].takeaways[0],'Listen first');
  assert.equal((await fetch(url,{method:'POST',headers:{'Content-Type':'application/json','x-test-owner':'1'},body:JSON.stringify({...record, person:''})})).status,400);
  const saved=await fetch(url,{method:'POST',headers:{'Content-Type':'application/json','x-test-owner':'1'},body:JSON.stringify({...record,purpose:'A stated interest',certainty:'Stated interest'})});assert.equal(saved.status,200);
  assert.equal(listPapaConversations(db,1)[0].purpose,'A stated interest');
  assert.equal(listPapaConversations(db,2)[0].person,'Other owner');
} finally { await new Promise<void>((resolve,reject)=>server.close(e=>e?reject(e):resolve()));db.close(); }
console.log('✓ Conversation persistence, owner isolation, validation, views, and protected HTTP routes');
